/* eslint-disable @typescript-eslint/explicit-function-return-type */
import { createHash } from 'node:crypto'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const workspace = resolve(root, '..')
const source = await readFile(resolve(root, 'packages/ola-design/tokens.json'), 'utf8')
const tokens = JSON.parse(source)
const sourceHash = createHash('sha256').update(source).digest('hex')
const checking = process.argv.includes('--check')
const formatting = await resolveConfig(resolve(root, 'package.json'))
if (tokens.schemaVersion !== 1) throw new Error('Unsupported Ola design schema')
const names = Object.keys(tokens.colors.light)
if (names.join() !== Object.keys(tokens.colors.dark).join()) {
  throw new Error('Light and dark token names must match')
}
const kebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)
const luminance = (hex) => {
  if (!/^#[0-9a-f]{6}$/i.test(hex)) throw new Error(`Invalid color: ${hex}`)
  const rgb = hex
    .slice(1)
    .match(/../g)
    .map((byte) => parseInt(byte, 16) / 255)
  const linear = rgb.map((value) =>
    value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4
  )
  return linear[0] * 0.2126 + linear[1] * 0.7152 + linear[2] * 0.0722
}
for (const [mode, palette] of Object.entries(tokens.colors)) {
  Object.values(palette).forEach(luminance)
  for (const [foreground, background] of [
    ['text', 'canvas'],
    ['text', 'surface'],
    ['textSecondary', 'surface'],
    ['textTertiary', 'surface'],
    ['onPrimary', 'primary'],
    ['onPrimarySoft', 'primarySoft'],
    ['link', 'surface'],
    ['success', 'successSoft'],
    ['warning', 'warningSoft'],
    ['danger', 'dangerSoft']
  ]) {
    const a = luminance(palette[foreground])
    const b = luminance(palette[background])
    const contrast = (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05)
    if (contrast < 4.5)
      throw new Error(`${mode} ${foreground}/${background}: ${contrast.toFixed(2)} < 4.5`)
  }
}
const declarations = (palette) =>
  names.map((key) => `  --ola-${kebab(key)}: ${palette[key]};`).join('\n')
const css = `/* Generated by scripts/sync-ola-design.mjs; version ${tokens.version}; sha256 ${sourceHash} */\n:root, .theme-light, [data-theme="light"] {\n${declarations(tokens.colors.light)}\n  --ola-radius-control: ${tokens.radius.control}px;\n  --ola-radius-panel: ${tokens.radius.panel}px;\n  --ola-radius-dialog: ${tokens.radius.dialog}px;\n  --ola-motion-feedback: ${tokens.motion.feedback}ms;\n  --ola-motion-transition: ${tokens.motion.transition}ms;\n}\n.dark, .theme-dark, [data-theme="dark"] {\n${declarations(tokens.colors.dark)}\n}\n@media (prefers-color-scheme: dark) {\n  :root:not(.light):not(.dark):not([data-theme]) {\n${declarations(tokens.colors.dark)}\n  }\n}\n`
const ts = `// Generated by scripts/sync-ola-design.mjs. Do not edit.\nexport const OLA_DESIGN_VERSION = '${tokens.version}'\nexport const OLA_DESIGN_SOURCE_HASH = '${sourceHash}'\nexport const OLA_DESIGN = ${JSON.stringify(tokens, null, 2)} as const\n`
const kotlin = `// Generated by Ola/scripts/sync-ola-design.mjs. Do not edit.\npackage chat.olaai.mobile.ui.theme\n\nimport androidx.compose.ui.graphics.Color\n\nobject OlaDesignTokens {\n    const val version = "${tokens.version}"\n    const val sourceHash = "${sourceHash}"\n${Object.entries(
  tokens.colors
)
  .map(
    ([mode, palette]) =>
      `    object ${mode === 'light' ? 'Light' : 'Dark'} {\n${names.map((key) => `        val ${key} = Color(0xFF${palette[key].slice(1)})`).join('\n')}\n    }`
  )
  .join('\n')}\n}\n`
const swift = `// Generated by Ola/scripts/sync-ola-design.mjs. Do not edit.\nimport UIKit\n\nenum OlaDesignTokens {\n    static let version = "${tokens.version}"\n    static let sourceHash = "${sourceHash}"\n${names.map((key) => `    static let ${key} = adaptive(0x${tokens.colors.light[key].slice(1)}, 0x${tokens.colors.dark[key].slice(1)})`).join('\n')}\n\n    private static func adaptive(_ light: UInt32, _ dark: UInt32) -> UIColor {\n        UIColor { traits in\n            let rgb = traits.userInterfaceStyle == .dark ? dark : light\n            return UIColor(red: CGFloat((rgb >> 16) & 0xFF) / 255,\n                           green: CGFloat((rgb >> 8) & 0xFF) / 255,\n                           blue: CGFloat(rgb & 0xFF) / 255, alpha: 1)\n        }\n    }\n}\n`
const outputs = new Map([
  ['Ola/src/renderer/src/assets/ola-design-tokens.css', css],
  ['Ola/src/renderer/src/lib/ola-design-tokens.ts', ts],
  ['Ola-admin/src/design/tokens.css', css],
  ['Ola-admin/src/design/tokens.ts', ts],
  [
    'ola-mobile/src/android/app/src/main/java/chat/olaai/mobile/ui/theme/OlaDesignTokens.kt',
    kotlin
  ],
  ['ola-mobile/src/ios/Shared/OlaDesignTokens.swift', swift]
])
const accent = {
  colors: Object.entries(tokens.colors).map(([mode, palette]) => ({
    ...(mode === 'dark' ? { appearances: [{ appearance: 'luminosity', value: 'dark' }] } : {}),
    color: {
      'color-space': 'srgb',
      components: Object.fromEntries([
        ...['red', 'green', 'blue'].map((name, index) => [
          name,
          (parseInt(palette.primary.slice(1 + index * 2, 3 + index * 2), 16) / 255).toFixed(6)
        ]),
        ['alpha', '1.000000']
      ])
    },
    idiom: 'universal'
  })),
  info: { author: 'xcode', version: 1 }
}
outputs.set(
  'ola-mobile/src/ios/Assets.xcassets/AccentColor.colorset/Contents.json',
  JSON.stringify(accent, null, 2) + '\n'
)
for (const [path, contents] of outputs) {
  const parser = path.endsWith('.ts')
    ? 'typescript'
    : path.endsWith('.css')
      ? 'css'
      : path.endsWith('.json')
        ? 'json'
        : null
  if (parser) outputs.set(path, await format(contents, { ...formatting, parser }))
}
const manifest =
  JSON.stringify(
    {
      schemaVersion: tokens.schemaVersion,
      version: tokens.version,
      sourceHash,
      files: Object.fromEntries(
        [...outputs].map(([path, contents]) => [
          path,
          createHash('sha256').update(contents).digest('hex')
        ])
      )
    },
    null,
    2
  ) + '\n'
outputs.set('Ola/packages/ola-design/generated/manifest.json', manifest)
let failed = false
for (const [path, contents] of outputs) {
  const target = resolve(workspace, path)
  if (checking) {
    const existing = await readFile(target, 'utf8').catch(() => null)
    if (existing !== contents) {
      console.error(`Out of sync: ${path}`)
      failed = true
    }
  } else {
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, contents)
  }
}
if (failed) process.exitCode = 1
else
  console.log(
    `Ola design ${tokens.version}: ${outputs.size} outputs ${checking ? 'verified' : 'generated'}; contrast pairs passed`
  )
